/** Build src-client/*.js into the single client module the Harness loads. */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.join(HERE, 'src-client')
const ORDER = [
  '00-core.js',
  '10-markdown.js',
  '12-mermaid.js',
  '14-diffflazy.js',
  '15-git.js',
  '20-code.js',
  '22-defs.js',
  '24-modal.js',
  '25-search.js',
  '26-filesearch.js',
  '27-sync.js',
  '28-gitgraph.js',
  '30-tree.js',
  '32-workbench.js',
  '34-html.js',
  '40-tabs.js',
  '45-json.js',
  '50-app.js',
]
const pkg = JSON.parse(fs.readFileSync(path.join(HERE, 'package.json'), 'utf8'))

/**
 * Strip the comments and the indentation of a source file.
 *
 * CONSERVATIVE on purpose: only whole-line `//` and `/* ... *\/` comments are
 * removed and every remaining line is trimmed. Nothing inside a string, a
 * regex or a template literal is touched - a line that merely CONTAINS `//`
 * (a URL, a regex) stays exactly as it is.
 *
 * Why: the Harness serves the plugin clients of ALL plugins as ONE bundle
 * script, and the local plugins' files are read from the workspace on every
 * boot. The reader's client was the biggest of them (418 KB of comments and
 * indentation); the smaller it is, the less the boot has to read and serve.
 */
function slim(text) {
  const out = []
  let inBlock = false
  for (const line of text.split('\n')) {
    const trimmed = line.trim()
    if (inBlock) {
      if (trimmed.includes('*/')) inBlock = false
      continue
    }
    if (trimmed.startsWith('/*')) {
      if (!trimmed.includes('*/')) inBlock = true
      continue
    }
    if (trimmed.startsWith('//')) continue
    if (!trimmed) continue
    out.push(trimmed)
  }
  return out.join('\n')
}

const parts = ORDER.map((file) => {
  const full = path.join(SRC, file)
  if (!fs.existsSync(full)) throw new Error(`missing client source: ${file}`)
  return `// ---- ${file} ----\n${slim(fs.readFileSync(full, 'utf8'))}`
})

/* Build id: a short hash of the client sources.
   Why: the Harness serves plugin clients as an IMMUTABLE, one-year-cached
   asset whose URL carries a `rev` derived from the bundle's file metadata,
   captured when the plugin is registered. A rebuilt bundle therefore does NOT
   reach a browser that already loaded the plugin - the bytes are re-read only
   when the plugin is re-registered (or an HMR watch reports a rebuild).
   The client compares this id with the one the Host serves
   (`GET /api/client-build`) and reloads itself when they differ, so a stale
   browser heals on the next page load instead of silently running old code. */
/**
 * The bundle template.
 *
 * The build id is the hash of the WHOLE bundle (the template included), not
 * only of the sources: a change in the wrapper must produce a new id, or the
 * running window would not reload and would keep the old wrapper.
 */
const template = (id) => `/* Generated by build.mjs from src-client/*.js. Do not edit directly. */
(function markdownReaderBoot(attempt) {
  // The Harness ABORTS the whole web boot when a plugin client fails to
  // import ("web boot: 1 entry did not activate" -> the app shows the crash
  // dialog and the user has to restart it). The loader is not guaranteed to
  // exist when this script runs, so WAIT for it instead of throwing: a missing
  // loader must never take the whole application down.
  var loader = (typeof window !== 'undefined' && window.__ModuleLoader__) || null;
  if (!loader || typeof loader.load !== 'function') {
    if (attempt < 60 && typeof window !== 'undefined' && window.setTimeout) {
      window.setTimeout(function () { markdownReaderBoot(attempt + 1); }, 50);
    }
    return;
  }
  loader.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    'use strict';
    const React = require('react');
    const h = React.createElement;
    const BUILD_ID = ${JSON.stringify(id)};
    let __slots = null;
    // A broken slice must degrade the READER, not the application, so the
    // slices run inside a guarded IIFE and the module still loads.
    try {
      __slots = (() => {
${parts.join('\n')}
        return { registerSlots };
      })();
    } catch (error) {
      if (typeof console !== 'undefined' && console.error) console.error('[markdown-reader] client init failed:', error);
    }
    return {
      inject: ['slots'],
      apply(ctx) {
        try {
          if (__slots && typeof __slots.registerSlots === 'function') __slots.registerSlots(ctx);
        } catch (error) {
          if (typeof console !== 'undefined' && console.error) console.error('[markdown-reader] apply failed:', error);
        }
      },
    };
  },
});
})();
`

const buildIdFull = crypto.createHash('sha1').update(template('000000000000')).digest('hex').slice(0, 12)
const out = template(buildIdFull)

/**
 * Write the bundle ATOMICALLY.
 *
 * The Harness reads `client.js` from this directory when the app boots (the
 * plugin is a junction into the workspace). A plain write leaves a truncated
 * file behind for a moment, and an app that boots in that window gets a
 * half-written script: the plugin's client fails to import and the whole web
 * boot aborts -> the app shows 「应用无法启动或已意外停止」. Writing to a
 * temporary file and renaming it means the file is ALWAYS complete.
 */
const target = path.join(HERE, 'client.js')
const tmp = path.join(HERE, 'client.js.tmp')
fs.writeFileSync(tmp, out, 'utf8')
fs.renameSync(tmp, target)
fs.writeFileSync(
  path.join(HERE, 'client.build.json'),
  JSON.stringify({ build: buildIdFull, at: new Date().toISOString(), bytes: Buffer.byteLength(out) }, null, 2) + '\n',
  'utf8',
)
console.log(`client.js written (${(out.length / 1024).toFixed(1)} KB) from ${ORDER.length} parts, build ${buildIdFull}`)
