/** Build src-client/*.js into the single client module the Harness loads. */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.join(HERE, 'src-client')
const ORDER = [
  '00-core.js',
  '10-markdown.js',
  '12-mermaid.js',
  '15-git.js',
  '20-code.js',
  '22-defs.js',
  '24-modal.js',
  '25-search.js',
  '27-sync.js',
  '28-gitgraph.js',
  '30-tree.js',
  '32-workbench.js',
  '34-html.js',
  '40-tabs.js',
  '45-json.js',
  '50-app.js',
]
const pkg = JSON.parse(fs.readFileSync(path.join(HERE, 'package.json'), 'utf8'))

const parts = ORDER.map((file) => {
  const full = path.join(SRC, file)
  if (!fs.existsSync(full)) throw new Error(`missing client source: ${file}`)
  return `// ---- ${file} ----\n${fs.readFileSync(full, 'utf8')}`
})

/* Build id: a short hash of the client sources.
   Why: the Harness serves plugin clients as an IMMUTABLE, one-year-cached
   asset whose URL carries a `rev` derived from the bundle's file metadata,
   captured when the plugin is registered. A rebuilt bundle therefore does NOT
   reach a browser that already loaded the plugin - the bytes are re-read only
   when the plugin is re-registered (or an HMR watch reports a rebuild).
   The client compares this id with the one the Host serves
   (`GET /api/client-build`) and reloads itself when they differ, so a stale
   browser heals on the next page load instead of silently running old code. */
const buildId = crypto.createHash('sha1').update(parts.join('\n')).digest('hex').slice(0, 12)

const out = `/* Generated by build.mjs from src-client/*.js. Do not edit directly. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    'use strict';
    const React = require('react');
    const h = React.createElement;
    const BUILD_ID = ${JSON.stringify(buildId)};
${parts.join('\n')}
    return {
      inject: ['slots'],
      apply(ctx) {
        registerSlots(ctx);
      },
    };
  },
});
`

fs.writeFileSync(path.join(HERE, 'client.js'), out, 'utf8')
fs.writeFileSync(
  path.join(HERE, 'client.build.json'),
  JSON.stringify({ build: buildId, at: new Date().toISOString(), bytes: Buffer.byteLength(out) }, null, 2) + '\n',
  'utf8',
)
console.log(`client.js written (${(out.length / 1024).toFixed(1)} KB) from ${ORDER.length} parts, build ${buildId}`)
